import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = process.env.CBYS_FIXTURES_DIR
  ? resolve(process.env.CBYS_FIXTURES_DIR)
  : fileURLToPath(new URL('../../fixtures/live-2026-11-22/', import.meta.url));

async function readJson(file) {
  return JSON.parse(await readFile(resolve(directory, file), 'utf8'));
}

const manifest = await readJson('manifest.json');
const responses = {};
for (const [path, { file, status }] of Object.entries(manifest.requests)) {
  if (path.startsWith('/api/v1/search.json?') || path.startsWith('/api/v1/merchants/')) {
    responses[path] = { status, body: await readJson(file) };
  }
}

const output = new URL('../demo/fixtures.js', import.meta.url);
const entries = Object.entries(responses).map(
  ([path, response]) => `    ${JSON.stringify(path)}: ${JSON.stringify(response)},`,
);
const source = [
  '// Generated by scripts/build-demo-fixtures.mjs. Snapshot for offline use.',
  'globalThis.CbysDemoFixtures = {',
  `  capturedOn: ${JSON.stringify(manifest.captured_at.slice(0, 10))},`,
  '  responses: {',
  ...entries,
  '  },',
  '};',
  '',
].join('\n');
await writeFile(output, source);
